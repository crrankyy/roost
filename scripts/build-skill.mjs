#!/usr/bin/env node
// Builds the self-contained parts of skill/roost-report from docs/design-system/ (re-run when the DS changes):
// the report template (ReportExample with /_ds/ links), the report-layer and chart cards, and a copy of the CLI.
import { copyFileSync, readFileSync, writeFileSync, chmodSync } from 'node:fs';

const DS = 'docs/design-system/components';
const OUT = 'skill/roost-report';
const toServed = (html) => html
  .replace(/^<!-- @dsCard[^\n]*\n/, '')
  .replace('<link rel="stylesheet" href="../reports.css">', '<link rel="stylesheet" href="/_ds/lynx-reports/v1/tokens.css">\n<link rel="stylesheet" href="/_ds/lynx-reports/v1/components/reports.css">')
  .replace('<script src="../reports.js"></script>', '<script src="/_ds/lynx-reports/v1/components/reports.js"></script>')
  .replace(/<title>[^<]*<\/title>/, '<title>REPORT TITLE</title>')
  .replace('<html>', '<html lang="en">');

writeFileSync(`${OUT}/template/index.html`, toServed(readFileSync(`${DS}/ReportExample/preview.html`, 'utf8')));

const cards = (names) => names.map((n) => readFileSync(`${DS}/${n}/README.md`, 'utf8').trim()).join('\n\n---\n\n');
const header = (title) => `<!-- GENERATED by scripts/build-skill.mjs from docs/design-system/. Do not edit here. -->\n\n# ${title}\n\n`;
writeFileSync(`${OUT}/reference/components.md`, header('Report layer components') + cards(['ReportExample', 'ReportHeader', 'ReportToc', 'KindBadge', 'ReportBadge', 'Stat', 'Finding', 'SubjectCard', 'ReportTable', 'ExpandableList', 'BudgetStack', 'Steps', 'Timeline', 'Callout', 'Verdict', 'CodeBlock', 'Figure', 'SourceList']));
writeFileSync(`${OUT}/reference/charts.md`, header('Charts') + cards(['Chart', 'BarList', 'ShareBar', 'Sparkline']));
const chartExample = readFileSync(`${DS}/Chart/preview.html`, 'utf8').match(/<body[^>]*>([\s\S]*)<\/body>/)[1].replace(/<script[\s\S]*?<\/script>/g, '').trim();
writeFileSync(`${OUT}/reference/chart-example.html`, `<!-- GENERATED: the Chart card's example markup (line chart, legend, data table). Copy the structure, not the data. -->\n${chartExample}\n`);
copyFileSync('cli/roost.mjs', `${OUT}/bin/roost.mjs`);
chmodSync(`${OUT}/bin/roost.mjs`, 0o755);
console.log('skill/roost-report rebuilt');
