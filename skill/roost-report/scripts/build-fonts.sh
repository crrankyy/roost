#!/bin/sh
# Builds fonts-dist/: the report faces as woff2 files plus report-type.css and report-mono.css, which Roost serves at
# /_fonts/v1/ (scripts/upload-fonts.mjs uploads them). Reports link those two stylesheets and never embed a font.
# The CSS names the files relatively, so it works from /_fonts/v1/ and from fonts-dist/ (the gallery) alike.
# fonts-dist/ is gitignored: MonoLisa is licensed, so its files never go into the repository.
# Usage: scripts/build-fonts.sh [path-to-MonoLisa-folder]   (default ~/misc/fonts/MonoLisa)
set -eu
SRC=${1:-$HOME/misc/fonts/MonoLisa}
HERE=$(cd "$(dirname "$0")/.." && pwd)
FONTS="$HERE/assets/fonts"
OUT="$HERE/fonts-dist"
mkdir -p "$OUT"
# Latin, punctuation, arrows, maths, box drawing (file trees), shapes, check marks, Powerline.
U="U+0020-007E,U+00A0-00FF,U+0131,U+0152-0153,U+2010-2027,U+2030-203A,U+2044,U+20AC,U+2122,U+2190-21FF,U+2200-22FF,U+2300-23FF,U+2500-259F,U+25A0-25FF,U+2713-2717,U+E0A0-E0A3,U+E0B0-E0BF"
subset() { uv run --quiet --with fonttools --with brotli pyftsubset "$1" --unicodes="$U" --flavor=woff2 --layout-features='*' --output-file="$2" 2>/dev/null; }

MONO="$OUT/report-mono.css"
printf '/* Report Mono: MonoLisa, subset for reports. Generated by scripts/build-fonts.sh; do not edit. */\n' > "$MONO"
for pair in "Regular:400:normal" "Regular Italic:400:italic" "Bold:700:normal" "Bold Italic:700:italic"; do
  style=${pair%%:*}; rest=${pair#*:}; weight=${rest%%:*}; fstyle=${rest#*:}
  name="report-mono-$weight-$fstyle.woff2"
  subset "$SRC/MonoLisa $style Nerd Font Complete Mono.otf" "$OUT/$name"
  # The source Bold Italic's CFF name contains a space, which Chrome's font sanitizer rejects
  # ("Failed to parse Name INDEX"). Give every face a clean PostScript name.
  uv run --quiet --with fonttools --with brotli python -I -c '
import sys
from fontTools.ttLib import TTFont
f = TTFont(sys.argv[1]); f["CFF "].cff.fontNames = [sys.argv[2]]; f.flavor = "woff2"; f.save(sys.argv[1])
' "$OUT/$name" "ReportMono-$(echo "$style" | tr -d ' ')"
  printf '@font-face { font-family: "Report Mono"; font-weight: %s; font-style: %s; font-display: swap; src: url(%s) format("woff2"); }\n' \
    "$weight" "$fstyle" "$name" >> "$MONO"
done

# Heading face: Black Chancery as "Report Display" (one weight; missing glyphs fall through to Report Mono).
# Body text (Coolvetica) is never built, served or embedded: its Typodermic desktop EULA forbids it.
TYPE="$OUT/report-type.css"
subset "$FONTS/black-chancery/BLKCHCRY.TTF" "$OUT/report-display.woff2"
printf '/* Report Display. Generated by scripts/build-fonts.sh; do not edit. */\n@font-face { font-family: "Report Display"; font-weight: 400; font-style: normal; font-display: swap; src: url(report-display.woff2) format("woff2"); }\n' > "$TYPE"

# Check: five faces, each with a non-trivial file.
[ "$(grep -c '@font-face' "$MONO")" -eq 4 ] || { echo "expected 4 mono faces" >&2; exit 1; }
for f in "$OUT"/*.woff2; do [ "$(wc -c < "$f")" -gt 10000 ] || { echo "$f looks empty" >&2; exit 1; }; done
ls -l "$OUT"
